// Grammars whose words are foams: typed 2-complexes swept in time (docs/theory.md, §7; decision 0004).
//
// A foam is morphe's worldline complex of a record of encounters with labels: its vertices are events in time, each with a kind; its
// edges are the segments of participants (each between two consecutive events it attends), labelled by the participant's kind; its
// faces are the lenses of pairs (each between two consecutive meetings of a pair, bounded by both participants' worldlines between
// them), labelled by the pair's kind. The first and the last vertex may be marked as the moments at the ends of the record (∂₀, ∂₁),
// at which every participant then alive is present.
//
// A foam is generated by sweeping time: each event attaches one vertex together with its star, the ends of the segments that arrive
// and leave and the corners of the lenses that open, close or pass there. Read as a production, a star rewrites the network of the
// moment (the participants alive, the lenses open between them): its left side is what it consumes (the participants it touches that
// were alive, the lenses it closes), its right side what it leaves (the participants that go on or begin, the lenses it opens); the
// participants that go on are its interface. The star of a vertex v is
//
//   - its kind;
//   - each participant present, with its role: through (an end arrives and one leaves), begins (only one leaves), ends (only one
//     arrives), instant (neither);
//   - its corners: a lens of the pair {a, b} that begins at v opens between a and b; one that ends at v closes between them; one that
//     runs past v along a's worldline passes on a.
//
// Four keys are read from a star, each a canonical form of a labelled multigraph (morphe's `canonical_form`): the event a node
// joined to each participant's node, an open or a close corner an edge between two participants, a pass a loop:
//   star     everything, with each participant's state where states are given;
//   rule     the event's action: its kind, the participants' kinds and roles, the open and close corners (no passes, no states);
//   match    what the event consumes: the participants with an arriving end, by kind, and the close corners among them;
//   context  the match with those participants' states and their passes (the lenses open on their other sides).
// Two stars have equal keys exactly when their structures are isomorphic. A key whose graph has no edge between two participants
// (no open or close corner among them: the event and its participants with their loops) is the sorted list of the participants'
// labels with their loops, exact for such graphs and cheap for an event that touches hundreds of participants; any other is the
// canonical form, exact where its search stays within its bound (which is reported).
//
// Two facts are exact for every foam. Each segment has one end at each of its vertices and each lens one open and one close corner,
// so that, with κ(v) = 1 − ends(v)/2 + (opens(v) + closes(v))/2, the Euler characteristic is local: χ = V − E + F = Σ_v κ(v)
// (Proposition 7.1). An event that touches one participant and opens or closes no lens (an observation of one building) has κ = 0,
// so such events can be added or removed without changing χ; one that joins n participants passing through has κ = 1 − n, the n
// worldlines pinched at one vertex. And two
// events are ordered when a worldline runs from one to the other: the causal order of the record's trace, events on disjoint
// participants commuting; its Foata steps, each event one step after the latest event before it on any of its worldlines.

