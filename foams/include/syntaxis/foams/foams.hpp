struct Foam {
  mt::Encounters encounters;
  mt::WorldlineComplex W;
  std::vector<std::string> vertex;       // each vertex's kind
  std::vector<double> time;              // each vertex's time, nondecreasing
  std::vector<char> boundary;            // whether a vertex is a moment at the ends of the record (∂₀, ∂₁)
  std::vector<std::string> participant;  // each participant's kind
  std::vector<std::string> pair;         // each pair's kind
  // A participant's state from a vertex on (optional): states[x] maps vertices to states; the state of x at v is the one given at
  // the latest vertex at or before v, and none before the first (an empty state is none). The context of the event at v sees the
  // state at v itself, so a caller who wants a context to hold only what came before gives at each vertex the state carried into
  // its event, never what the event does.
  std::vector<std::map<std::size_t, std::string>> states;

  std::size_t size() const { return vertex.size(); }
  std::string state(std::size_t x, std::size_t v) const {
    if (x >= states.size() || states[x].empty()) return {};
    auto it = states[x].upper_bound(v);
    if (it == states[x].begin()) return {};
    return std::prev(it)->second;
  }
};

// A foam from a record of encounters and its labels; the worldline complex is built here.
inline Foam make(mt::Encounters E, std::vector<std::string> vertex, std::vector<double> time, std::vector<char> boundary,
                 std::vector<std::string> participant, std::vector<std::string> pair) {
  const std::size_t V = E.present.size();
  detail::require(vertex.size() == V && time.size() == V && boundary.size() == V, "a kind, a time and a boundary flag for every vertex");
  detail::require(participant.size() == E.participants && pair.size() == E.pairs.size(), "a kind for every participant and every pair");
  for (std::size_t v = 1; v < V; v++) detail::require(time[v] >= time[v - 1], "times nondecreasing in the order of the vertices");
  Foam F;
  F.W = mt::worldline_complex(E);
  F.encounters = std::move(E);
  F.vertex = std::move(vertex), F.time = std::move(time), F.boundary = std::move(boundary);
  F.participant = std::move(participant), F.pair = std::move(pair);
  return F;
}

struct Corner {
  enum Kind : int { open = 0, close = 1, pass = 2 };
  Kind kind = open;
  std::size_t lens = 0;   // in W.lenses
  std::size_t a = 0, b = 0;  // positions among the star's participants (b == a for a pass)
};

struct Star {
  std::size_t vertex = 0;
  bool boundary = false;
  std::vector<std::size_t> participants;  // in the order of the record's presence
  std::vector<char> in, out;              // whether each has an arriving and a leaving end
  std::vector<Corner> corners;
  int ends = 0, opens = 0, closes = 0, passes = 0;
  double kappa = 0;                       // 1 − ends/2 + (opens + closes)/2
  std::string star, rule, match, context;  // canonical keys (a boundary vertex: its kind alone)
  bool exact = true;                      // every key an exact canonical form
};

inline const char* role(bool in, bool out) { return in && out ? "through" : out ? "begins" : in ? "ends" : "instant"; }

namespace detail {
struct Keyed {
  std::string code;
  bool exact = true;
};
inline Keyed key(const mc::LabelledGraph& G) {
  const auto c = mc::canonical_form(G);
  return {c.code, c.exact};
}
inline std::string corner_label(Corner::Kind k, const std::string& pair) {
  return std::string(k == Corner::open ? "open:" : k == Corner::close ? "close:" : "pass:") + pair;
}
// The key of a graph whose only edges join a root to each other node, with loops: the root's label and the other nodes' labels,
// each with its loops' labels sorted, the nodes sorted. Two such graphs are isomorphic exactly when these keys are equal.
inline std::string flat_key(const mc::LabelledGraph& G) {
  std::vector<std::vector<std::string>> loops(G.vertex.size());
  for (const auto& [u, v, label] : G.edges)
    if (u == v) loops[u].push_back(label);
  std::vector<std::string> nodes;
  for (std::size_t i = 1; i < G.vertex.size(); i++) {
    std::sort(loops[i].begin(), loops[i].end());
    std::string n = G.vertex[i];
    for (const auto& l : loops[i]) n += "\x1f" + l;
    nodes.push_back(n);
  }
  std::sort(nodes.begin(), nodes.end());
  std::string out = "flat\x1e" + (G.vertex.empty() ? std::string() : G.vertex[0]);
  for (const auto& n : nodes) out += "\x1e" + n;
  return out;
}
// Whether every edge of a graph joins the root (node 0) to another node or is a loop.
inline bool flat(const mc::LabelledGraph& G) {
  for (const auto& [u, v, label] : G.edges)
    if (u != v && u != 0 && v != 0) return false;
  return true;
}
inline Keyed key_any(const mc::LabelledGraph& G) {
  if (flat(G)) return {flat_key(G), true};
  return key(G);
}
}  // namespace detail

// The star of every vertex.
inline std::vector<Star> stars(const Foam& F) {
  const auto& E = F.encounters;
  const auto& W = F.W;
  const std::size_t V = F.size();
  std::vector<Star> S(V);
  // Corners at each vertex: (kind, lens, participant a, participant b).
  struct Raw {
    Corner::Kind kind;
    std::size_t lens, a, b;
  };
  std::vector<std::vector<Raw>> at(V);
  const auto interior = [&](std::size_t x, std::size_t u, std::size_t w, std::size_t lens) {
    const auto& line = W.worldline[x];
    auto i = std::lower_bound(line.begin(), line.end(), u), j = std::lower_bound(line.begin(), line.end(), w);
    detail::require(i != line.end() && *i == u && j != line.end() && *j == w, "a lens's meetings on its participants' worldlines");
    for (auto k = i + 1; k < j; ++k) at[*k].push_back({Corner::pass, lens, x, x});
  };
  for (std::size_t f = 0; f < W.lenses.size(); f++) {
    const auto& l = W.lenses[f];
    const auto& p = E.pairs[l.pair];
    at[l.from].push_back({Corner::open, f, p.a, p.b});
    at[l.to].push_back({Corner::close, f, p.a, p.b});
    interior(p.a, l.from, l.to, f);
    interior(p.b, l.from, l.to, f);
  }
  for (std::size_t v = 0; v < V; v++) {
    Star& s = S[v];
    s.vertex = v, s.boundary = F.boundary[v] != 0;
    s.participants = E.present[v];
    std::map<std::size_t, std::size_t> pos;
    for (std::size_t i = 0; i < s.participants.size(); i++) pos[s.participants[i]] = i;
    for (auto x : s.participants) {
      const auto& line = W.worldline[x];
      const bool in = !line.empty() && line.front() != v, out = !line.empty() && line.back() != v;
      s.in.push_back(in), s.out.push_back(out);
      s.ends += in + out;
    }
    for (const auto& r : at[v]) {
      detail::require(pos.count(r.a) && pos.count(r.b), "a corner's participants present at its vertex");
      s.corners.push_back({r.kind, r.lens, pos[r.a], pos[r.b]});
      (r.kind == Corner::open ? s.opens : r.kind == Corner::close ? s.closes : s.passes)++;
    }
    s.kappa = 1 - s.ends / 2.0 + (s.opens + s.closes) / 2.0;
    if (s.boundary) {
      s.star = s.rule = s.match = s.context = "boundary:" + F.vertex[v];
      continue;
    }
    // The four keys.
    const std::size_t n = s.participants.size();
    mc::LabelledGraph star, rule, match, context;
    star.vertex.push_back("e:" + F.vertex[v]);
    rule.vertex.push_back("e:" + F.vertex[v]);
    match.vertex.push_back("m");
    context.vertex.push_back("m");
    std::vector<std::size_t> in_node(n, 0);  // a participant's node in the match and the context (0 where it has no arriving end)
    for (std::size_t i = 0; i < n; i++) {
      const auto x = s.participants[i];
      const std::string kind = F.participant[x], st = F.state(x, v);
      star.vertex.push_back("x:" + kind + (st.empty() ? "" : "|" + st) + "|" + role(s.in[i], s.out[i]));
      rule.vertex.push_back("x:" + kind + "|" + role(s.in[i], s.out[i]));
      star.edges.push_back({0, i + 1, "at"});
      rule.edges.push_back({0, i + 1, "at"});
      if (s.in[i]) {
        in_node[i] = match.vertex.size();
        match.vertex.push_back("x:" + kind);
        context.vertex.push_back("x:" + kind + (st.empty() ? "" : "|" + st));
        match.edges.push_back({0, in_node[i], "at"});
        context.edges.push_back({0, in_node[i], "at"});
      }
    }
    for (const auto& c : s.corners) {
      const std::string label = detail::corner_label(c.kind, F.pair[W.lenses[c.lens].pair]);
      star.edges.push_back({c.a + 1, c.b + 1, label});
      if (c.kind != Corner::pass) rule.edges.push_back({c.a + 1, c.b + 1, label});
      if (c.kind == Corner::close) {
        match.edges.push_back({in_node[c.a], in_node[c.b], label});
        context.edges.push_back({in_node[c.a], in_node[c.b], label});
      }
      if (c.kind == Corner::pass && in_node[c.a]) context.edges.push_back({in_node[c.a], in_node[c.a], label});
    }
    const auto ks = detail::key_any(star), kr = detail::key_any(rule), km = detail::key_any(match), kc = detail::key_any(context);
    s.star = ks.code, s.rule = kr.code, s.match = km.code, s.context = kc.code;
    s.exact = ks.exact && kr.exact && km.exact && kc.exact;
  }
  return S;
}

// The cells of a foam counted from its stars alone, and the Euler characteristic both ways (Proposition 7.1).
struct Replay {
  std::size_t vertices = 0, edges = 0, faces = 0;
  long euler = 0;          // V − E + F from the stars
  double local = 0;        // Σ κ(v)
  bool consistent = true;  // the ends pair up into the foam's segments and the corners into its lenses
};

inline Replay replay(const Foam& F, const std::vector<Star>& S) {
  Replay R;
  long ends = 0, opens = 0, closes = 0;
  for (const auto& s : S) ends += s.ends, opens += s.opens, closes += s.closes, R.local += s.kappa;
  R.vertices = S.size();
  R.consistent = ends % 2 == 0 && opens == closes && static_cast<std::size_t>(ends / 2) == F.W.segments.size() &&
                 static_cast<std::size_t>(opens) == F.W.lenses.size() && S.size() == F.size();
  R.edges = static_cast<std::size_t>(ends / 2), R.faces = static_cast<std::size_t>(opens);
  R.euler = static_cast<long>(R.vertices) - static_cast<long>(R.edges) + static_cast<long>(R.faces);
  return R;
}

// The Foata steps of the record's trace: an event's step is one more than the latest step of an event before it on one of its
// worldlines (the moments at the ends are no events and have none, −1); the width of each step and the depth.
struct Steps {
  std::vector<long> step;
  std::vector<std::size_t> width;
  std::size_t depth = 0;
};

inline Steps steps(const Foam& F) {
  const std::size_t V = F.size();
  std::vector<std::vector<std::size_t>> into(V);
  for (const auto& sg : F.W.segments) into[sg.to].push_back(sg.from);
  Steps S;
  S.step.assign(V, -1);
  for (std::size_t v = 0; v < V; v++) {
    if (F.boundary[v]) continue;
    long k = 0;
    for (auto u : into[v])
      if (!F.boundary[u]) k = std::max(k, S.step[u] + 1);
    S.step[v] = k;
    if (static_cast<std::size_t>(k) >= S.width.size()) S.width.resize(static_cast<std::size_t>(k) + 1, 0);
    S.width[static_cast<std::size_t>(k)]++;
  }
  S.depth = S.width.size();
  return S;
}

